export function extraLabels(locale: string): ExtraLabels {
  return locale.toLowerCase().startsWith('fr') ? FR : EN;
}

export function useExtraLabels(): ExtraLabels {
  const { locale } = useI18n();
  return useMemo(() => extraLabels(locale), [locale]);
}
