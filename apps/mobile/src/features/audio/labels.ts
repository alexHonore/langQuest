export function audioExtraLabels(locale: string): AudioExtraLabels {
  return locale.toLowerCase().startsWith('fr') ? FR : EN;
}

export function useAudioLabels(): AudioExtraLabels {
  const { locale } = useI18n();
  return useMemo(() => audioExtraLabels(locale), [locale]);
}
