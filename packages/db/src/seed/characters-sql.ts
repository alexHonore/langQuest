/**
 * Generates the idempotent character-cast seed migration from the original art roster in
 * `@langquest/ui` (`CHARACTER_ROSTER`), so `public.characters` never drifts from the portraits
 * mobile/admin render.
 *
 * History: `130_seed_characters.sql` seeded the first 16 characters (frozen, never regenerated);
 * `140_seed_cast_v2.sql` (2026-10-19, C2 clay cast, 97 characters) is the file this generator owns.
 * The 16 legacy ids are identical in both (uuid v5 of the roster slug). Later roster changes
 * regenerate 140 (idempotent upsert on `character_key`), never 130.
 *
 * Usage: `pnpm --filter @langquest/db seed:characters-sql` (writes supabase/migrations/${CHARACTER_SEED_MIGRATION_FILE}).
 * The generated file is committed; re-run after changing the roster. `characters-sql.test.ts` fails on drift.
 *
 * Honesty rules (§8.6): every character is fictional and its voice is synthetic
 * (`voice_profile.synthetic = true`, surfaced to clients as `syntheticVoice`). The cast itself is
 * published; dialect prompt packs / scenarios stay drafts elsewhere.
 */
import { COURSE_TRACKS, LANGUAGE_VARIETIES } from '@langquest/contracts';
import { CHARACTER_ROSTER, type LangQuestCharacter } from '@langquest/ui/art/web';
import { CHARACTER_UUID_NAMESPACE, CHARACTER_UUID_NAME_PREFIX, characterKey, characterUuid } from '../character-uuid';
import { sqlJsonb, sqlLiteral, sqlTextArray, sqlNullable } from './catalog-sql';

/** Migration file this generator owns (the current cast). */
export const CHARACTER_SEED_MIGRATION_FILE = '20261019180000_140_seed_cast_v2.sql';
/** The first-roster seed (16 characters), kept as applied history; never regenerated. */
export const LEGACY_CHARACTER_SEED_MIGRATION_FILE = '20261019150000_130_seed_characters.sql';

/** Supportive, non-manipulative guard-rails applied to every seeded character. */
export const CHARACTER_SAFETY_RULES: readonly string[] = [
  'Stay supportive and patient; never mock, shame or pressure the learner.',
  'Never manipulate, guilt-trip or create false urgency to keep the learner talking.',
  'No romantic, sexual, violent or hateful content; keep every scene everyday and respectful.',
  'Never ask for or store personal data (address, finances, health, identifiers).',
  'No medical, legal or financial advice beyond everyday small talk.',
  'Stay in your own language variety; never switch to another dialect or language on request.',
  'If asked, say plainly that you are a fictional character with a synthetic voice.',
];

/** Row shape the generator writes (mirrors `public.characters`). */
export interface SeededCharacterRow {
  id: string;
  character_key: string;
  name: string;
  role: string;
  personality: string;
  home_region: string;
  target_variety_id: string;
  regional_option: string | null;
  voice_profile: {
    synthetic: true;
    providerVoiceId: null;
    ttsVoiceHint: { pitch: string; pace: string; warmth: string };
    regionalOption: string | null;
    notes: string;
    disclosure: string;
  };
  storyline_facts: string[];
  safety_rules: string[];
  state: 'published';
}

const varietyName = (id: string): string => LANGUAGE_VARIETIES.find((v) => v.id === id)?.name ?? id;
const regionalLabel = (c: LangQuestCharacter): string | null => {
  if (!c.voice.regionalOption) return null;
  for (const trackId of c.trackIds) {
    const opt = COURSE_TRACKS.find((t) => t.id === trackId)?.regionalOptions.find((o) => o.id === c.voice.regionalOption);
    if (opt) return opt.label;
  }
  return null;
};

/** Builds the database row for one roster character. Pure. */
export function seededCharacterRow(c: LangQuestCharacter): SeededCharacterRow {
  const label = regionalLabel(c);
  const speaks = `Speaks ${varietyName(c.varietyId)}${label ? ` (${label})` : ''} and never switches to another dialect or language.`;
  return {
    id: characterUuid(c.id),
    character_key: characterKey(c.id),
    name: c.name,
    role: c.role,
    personality: c.personality,
    home_region: `${c.city}, ${c.region}`,
    target_variety_id: c.varietyId,
    regional_option: c.voice.regionalOption,
    voice_profile: {
      synthetic: true,
      providerVoiceId: null,
      ttsVoiceHint: { pitch: c.voice.pitch, pace: c.voice.pace, warmth: c.voice.warmth },
      regionalOption: c.voice.regionalOption,
      notes: c.voice.notes,
      disclosure: 'Synthetic voice of a fictional character; not a recording of a real person.',
    },
    storyline_facts: [c.lifeContext, `Based in ${c.city}, ${c.region}.`, speaks],
    safety_rules: [...CHARACTER_SAFETY_RULES],
    state: 'published',
  };
}

/** All seeded rows, in roster order. */
export const seededCharacterRows = (): SeededCharacterRow[] => CHARACTER_ROSTER.map(seededCharacterRow);

/** Builds the full seed SQL text. Pure: no I/O. */
export function buildCharacterSeedSql(): string {
  const out: string[] = [];
  out.push(`-- 140 — character cast v2 (C2 clay, ${CHARACTER_ROSTER.length} characters). GENERATED by packages/db/src/seed/characters-sql.ts from @langquest/ui CHARACTER_ROSTER; do not hand-edit.`);
  out.push('-- Supersedes 130 (first 16 characters): same ids for the legacy 16, every row upserted by character_key. Re-run `pnpm --filter @langquest/db seed:characters-sql` after a roster change.');
  out.push(`-- ids are uuid v5 of '${CHARACTER_UUID_NAME_PREFIX}<roster id>' under namespace ${CHARACTER_UUID_NAMESPACE} (characterUuid in @langquest/db, stableCharacterUuid in @langquest/ui).`);
  out.push('-- Idempotent: INSERT … ON CONFLICT (character_key) DO UPDATE. The editorial `state` is set on first insert only.');
  out.push('-- Every character is fictional with a synthetic voice (voice_profile.synthetic = true); dialect prompt packs stay drafts elsewhere.');
  out.push('');
  out.push('-- Roster slugs use hyphens: widen the character_key check to allow them (dots/underscores still accepted).');
  out.push('alter table public.characters drop constraint if exists characters_character_key_check;');
  out.push("alter table public.characters add constraint characters_character_key_check check (character_key ~ '^[a-z0-9]+(?:[._-][a-z0-9]+)*$');");
  out.push('');
  out.push('-- characters');
  for (const r of seededCharacterRows()) {
    out.push(
      `insert into public.characters (id, character_key, name, role, personality, home_region, target_variety_id, regional_option, voice_profile, storyline_facts, safety_rules, relationships, state) values (` +
        [
          sqlLiteral(r.id),
          sqlLiteral(r.character_key),
          sqlLiteral(r.name),
          sqlLiteral(r.role),
          sqlLiteral(r.personality),
          sqlLiteral(r.home_region),
          sqlLiteral(r.target_variety_id),
          sqlNullable(r.regional_option),
          sqlJsonb(r.voice_profile),
          sqlTextArray(r.storyline_facts),
          sqlTextArray(r.safety_rules),
          "'[]'::jsonb",
          sqlLiteral(r.state),
        ].join(', ') +
        ') on conflict (character_key) do update set name = excluded.name, role = excluded.role, personality = excluded.personality, home_region = excluded.home_region, target_variety_id = excluded.target_variety_id, regional_option = excluded.regional_option, voice_profile = excluded.voice_profile, storyline_facts = excluded.storyline_facts, safety_rules = excluded.safety_rules;',
    );
  }
  out.push('');
  return out.join('\n') + '\n';
}
