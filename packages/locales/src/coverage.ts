/**
 * Localization coverage (spec §2.1 editorial honesty, CONVENTIONS §2.2).
 *
 * Two things live here:
 * 1. UI catalog coverage: which keys of the base (`en`) catalog each locale provides, per
 *    namespace. Feeds the admin "Languages / Locales" view and `coverage.json`.
 * 2. A generator for `course_source_localizations` rows. It is deliberately conservative:
 *    a (track, source) pair is `partial` (draft available) only when a curriculum seed is
 *    declared for it, `complete` only when that seed is fully native-reviewed, and
 *    `planned` otherwise. Nothing is ever marked available because a UI catalog exists.
 */
import {
  COURSE_TRACKS,
  LANGUAGE_CODES,
  type CoverageMetrics,
  type CoverageStatus,
  type CourseTrackId,
  type SourceLanguageCode,
  db,
  type InsertOf,
} from '@langquest/contracts';
import {
  BASE_LOCALE,
  CATALOGS,
  CATALOG_NAMESPACES,
  REQUIRED_PARTIAL_NAMESPACES,
  flattenCatalog,
  namespaceOfKey,
  type FlatCatalog,
  type MessageCatalog,
} from './catalogs';
import coverageJson from './catalogs/coverage.json';

// ---------------------------------------------------------------------------
// UI catalog coverage
// ---------------------------------------------------------------------------

export interface NamespaceCoverage {
  namespace: string;
  expected: number;
  present: number;
  missing: string[];
  /** 0..100 */
  pct: number;
}

export type LocaleCoverageStatus = 'complete' | 'partial' | 'missing';

export interface LocaleCoverage {
  locale: string;
  status: LocaleCoverageStatus;
  totalExpected: number;
  totalPresent: number;
  /** 0..100 */
  pct: number;
  namespaces: NamespaceCoverage[];
  /** Keys present in the locale but absent from the base catalog (drift to clean up). */
  extraKeys: string[];
  /** Keys whose value is an empty string. */
  emptyKeys: string[];
  /** Namespaces that are 100% translated. */
  completeNamespaces: string[];
  /** True when every `REQUIRED_PARTIAL_NAMESPACES` namespace is complete (locale is usable for onboarding). */
  usable: boolean;
}

const pct = (present: number, expected: number): number => (expected === 0 ? 100 : Math.round((present / expected) * 10000) / 100);

/** Coverage of one flat catalog against a flat base catalog. */
export function computeLocaleCoverage(locale: string, catalog: FlatCatalog, base: FlatCatalog): LocaleCoverage {
  const byNamespace = new Map<string, { expected: string[]; present: number; missing: string[] }>();
  for (const key of Object.keys(base)) {
    const ns = namespaceOfKey(key);
    let entry = byNamespace.get(ns);
    if (!entry) {
      entry = { expected: [], present: 0, missing: [] };
      byNamespace.set(ns, entry);
    }
    entry.expected.push(key);
    if (typeof catalog[key] === 'string' && catalog[key] !== '') entry.present += 1;
    else entry.missing.push(key);
  }
  const namespaces: NamespaceCoverage[] = [...byNamespace.entries()].map(([namespace, e]) => ({
    namespace,
    expected: e.expected.length,
    present: e.present,
    missing: e.missing,
    pct: pct(e.present, e.expected.length),
  }));
  const totalExpected = Object.keys(base).length;
  const totalPresent = namespaces.reduce((n, ns) => n + ns.present, 0);
  const extraKeys = Object.keys(catalog).filter((k) => !(k in base));
  const emptyKeys = Object.entries(catalog)
    .filter(([, v]) => v === '')
    .map(([k]) => k);
  const completeNamespaces = namespaces.filter((ns) => ns.present === ns.expected).map((ns) => ns.namespace);
  const status: LocaleCoverageStatus = totalPresent === 0 ? 'missing' : totalPresent === totalExpected ? 'complete' : 'partial';
  return {
    locale,
    status,
    totalExpected,
    totalPresent,
    pct: pct(totalPresent, totalExpected),
    namespaces,
    extraKeys,
    emptyKeys,
    completeNamespaces,
    usable: REQUIRED_PARTIAL_NAMESPACES.every((ns) => completeNamespaces.includes(ns)),
  };
}

/** Coverage for every locale in `catalogs` against `baseLocale`. */
export function computeCatalogCoverage(
  catalogs: Readonly<Record<string, MessageCatalog | FlatCatalog>> = CATALOGS,
  baseLocale: string = BASE_LOCALE,
): Record<string, LocaleCoverage> {
  const baseNested = catalogs[baseLocale];
  if (!baseNested) throw new Error(`Base locale ${baseLocale} has no catalog`);
  const base = flattenCatalog(baseNested as MessageCatalog);
  const out: Record<string, LocaleCoverage> = {};
  for (const [locale, nested] of Object.entries(catalogs)) {
    out[locale] = computeLocaleCoverage(locale, flattenCatalog(nested as MessageCatalog), base);
  }
  return out;
}

/** Shape of `catalogs/coverage.json` (checked in; regenerated by `buildCoverageMetadata`). */
export interface CoverageMetadata {
  baseLocale: string;
  namespaces: readonly string[];
  locales: Readonly<
    Record<
      string,
      {
        status: LocaleCoverageStatus;
        /** Namespaces that are fully translated. */
        namespaces: readonly string[];
        /** Fit for onboarding + enrollment management (all required namespaces complete). */
        usable: boolean;
      }
    >
  >;
}

export const COVERAGE_METADATA: CoverageMetadata = coverageJson as CoverageMetadata;

/** Build the metadata object from the bundled catalogs (tests assert it equals `coverage.json`). */
export function buildCoverageMetadata(): CoverageMetadata {
  const coverage = computeCatalogCoverage();
  const locales: Record<string, CoverageMetadata['locales'][string]> = {};
  for (const [locale, c] of Object.entries(coverage)) {
    locales[locale] = { status: c.status, namespaces: c.completeNamespaces, usable: c.usable };
  }
  return { baseLocale: BASE_LOCALE, namespaces: [...CATALOG_NAMESPACES], locales };
}

/** UI percentage per locale (0..100) for `course_source_localizations.metrics.ui_pct`. */
export function uiCoveragePctByLanguage(): Record<string, number> {
  const out: Record<string, number> = {};
  for (const [locale, c] of Object.entries(computeCatalogCoverage())) out[locale] = Math.round(c.pct);
  return out;
}

// ---------------------------------------------------------------------------
// course_source_localizations generator
// ---------------------------------------------------------------------------

export type CourseSourceLocalizationInsert = InsertOf<typeof db.CourseSourceLocalizationsTable>;

/** What the curriculum package actually has for one (track, source) pair. */
export interface CurriculumSeed {
  courseTrackId: CourseTrackId;
  sourceLanguageCode: SourceLanguageCode;
  /** 0..100; defaults to 0 when unknown. */
  missionInstructionsPct?: number;
  explanationsPct?: number;
  subtitlesPct?: number;
  audioOverlaysPct?: number;
  /** True only after a native reviewer signed the pair off. */
  nativeReviewed?: boolean;
  reviewerId?: string | null;
  reviewedAt?: string | null;
}

export interface GenerateLocalizationRowsOptions {
  /** Seeds that exist. Default: none (nothing has been seeded in this repository yet). */
  seeds?: readonly CurriculumSeed[];
  /** Pairs an editor explicitly marked unavailable (e.g. a source language the project will not support for a track). */
  unavailable?: ReadonlyArray<{ courseTrackId: CourseTrackId; sourceLanguageCode: SourceLanguageCode }>;
  /** Tracks to emit rows for. Default: all 30. */
  tracks?: readonly CourseTrackId[];
  /** Source languages to emit rows for. Default: every catalog language (23). */
  sourceLanguages?: readonly SourceLanguageCode[];
  /** UI translation percentage per language code. Default: computed from bundled catalogs (0 for locales without one). */
  uiPctByLanguage?: Readonly<Record<string, number>>;
}

const clampPct = (n: number | undefined): number => Math.max(0, Math.min(100, Math.round(n ?? 0)));

/**
 * Generate one `course_source_localizations` row per (track, source).
 *
 * Status rules (honest by construction):
 * - `unavailable`: listed in `options.unavailable`.
 * - `complete`: a seed exists, `nativeReviewed` is true and every metric is 100.
 * - `partial`: a seed exists but is not fully reviewed → editorial note `enrollment.coverage.draftAvailable`.
 * - `planned`: everything else, including pairs whose only asset is a UI catalog.
 *
 * `fallback_source_language_code` is `en` for non-complete rows whenever the English row
 * of the same track is at least partial; it is an opt-in suggestion for the learner,
 * never applied silently (spec §2.1, §15).
 */
export function generateCourseSourceLocalizationRows(options: GenerateLocalizationRowsOptions = {}): CourseSourceLocalizationInsert[] {
  const tracks = options.tracks ?? COURSE_TRACKS.map((t) => t.id);
  const sources = options.sourceLanguages ?? [...LANGUAGE_CODES];
  const uiPct = options.uiPctByLanguage ?? uiCoveragePctByLanguage();
  const seedKey = (t: string, s: string) => `${t}|${s}`;
  const seeds = new Map<string, CurriculumSeed>((options.seeds ?? []).map((s) => [seedKey(s.courseTrackId, s.sourceLanguageCode), s]));
  const unavailable = new Set((options.unavailable ?? []).map((u) => seedKey(u.courseTrackId, u.sourceLanguageCode)));

  const statusFor = (track: CourseTrackId, source: SourceLanguageCode): { status: CoverageStatus; metrics: CoverageMetrics; seed: CurriculumSeed | null } => {
    const metricsBase: CoverageMetrics = {
      mission_instructions_pct: 0,
      explanations_pct: 0,
      ui_pct: clampPct(uiPct[source]),
      subtitles_pct: 0,
      audio_overlays_pct: 0,
    };
    if (unavailable.has(seedKey(track, source))) return { status: 'unavailable', metrics: { ...metricsBase, ui_pct: 0 }, seed: null };
    const seed = seeds.get(seedKey(track, source));
    if (!seed) return { status: 'planned', metrics: metricsBase, seed: null };
    const metrics: CoverageMetrics = {
      mission_instructions_pct: clampPct(seed.missionInstructionsPct),
      explanations_pct: clampPct(seed.explanationsPct),
      ui_pct: metricsBase.ui_pct,
      subtitles_pct: clampPct(seed.subtitlesPct),
      audio_overlays_pct: clampPct(seed.audioOverlaysPct),
    };
    const allFull = Object.values(metrics).every((v) => v === 100);
    return { status: seed.nativeReviewed && allFull ? 'complete' : 'partial', metrics, seed };
  };

  const rows: CourseSourceLocalizationInsert[] = [];
  for (const track of tracks) {
    const english = statusFor(track, 'en');
    const englishUsable = english.status === 'complete' || english.status === 'partial';
    for (const source of sources) {
      const { status, metrics, seed } = statusFor(track, source);
      const noteKey =
        status === 'partial' ? 'enrollment.coverage.draftAvailable' : status === 'planned' ? 'enrollment.coverage.detail.planned' : status === 'unavailable' ? 'enrollment.coverage.detail.unavailable' : null;
      rows.push({
        course_track_id: track,
        source_language_code: source,
        status,
        metrics,
        native_reviewed: seed?.nativeReviewed ?? false,
        reviewer_id: seed?.reviewerId ?? null,
        reviewed_at: seed?.reviewedAt ?? null,
        editorial_note_key: noteKey,
        fallback_source_language_code: status !== 'complete' && status !== 'unavailable' && source !== 'en' && englishUsable ? 'en' : null,
      });
    }
  }
  return rows;
}

/** Validate generated rows against the contracts schema (throws on drift). */
export function validateCourseSourceLocalizationRows(rows: readonly CourseSourceLocalizationInsert[]): CourseSourceLocalizationInsert[] {
  return rows.map((row) => db.CourseSourceLocalizationsTable.insert.parse(row) as CourseSourceLocalizationInsert);
}
