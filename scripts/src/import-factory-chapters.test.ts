import { describe, expect, it } from 'vitest';
import { GENERATED_CHAPTERS, defineSeedChapter, type SeedChapter } from '@langquest/curriculum';
import { buildFrPrompt, checkMissionFr, copyChapter, curriculumChapter, generatedIndexSource, overlayFromFr, type MissionFr } from './import-factory-chapters';

/** The Russian chapter as content-factory drafts it: English only, the story arc's title key, no character voices. */
const russian = GENERATED_CHAPTERS.find((c) => c.courseTrackId === 'russian')!;
const draft: SeedChapter = defineSeedChapter({
  ...russian,
  key: 'russian_ch1_factory_en',
  sourceLanguages: ['en'],
  titles: { en: 'story.arrival.chapter1.title' },
  characters: russian.characters.map((c) => ({ ...c, voice: null })),
  missions: russian.missions.map((m) => ({ ...m, titles: { en: m.titles.en! }, sceneNotes: { en: m.sceneNotes.en! }, expressions: m.expressions.map((e) => ({ ...e, meanings: { en: e.meanings.en! } })) })),
});

const frFor = (m: SeedChapter['missions'][number]): MissionFr => ({
  title: `FR ${m.key}`,
  sceneNote: 'Vous êtes dans la rue.',
  characterVoice: 'female',
  expressions: m.expressions.map((e) => ({ key: e.key, meaning: `sens de ${e.key}`, contextNote: null, literalGloss: null })),
});

describe('import-factory-chapters', () => {
  it('asks for French from the target phrase, never to rewrite it', () => {
    const { system, user } = buildFrPrompt(draft, draft.missions[0]!);
    expect(system).toMatch(/Never translate, correct or rewrite the Russian phrases/);
    expect(system).toMatch(/Translate the MEANING from the Russian phrase itself/);
    expect(JSON.parse(user).phrases[0]).toMatchObject({ key: draft.missions[0]!.expressions[0]!.key, text: draft.missions[0]!.expressions[0]!.targetText });
  });

  it('refuses French text that does not cover exactly the mission’s phrases', () => {
    const m = draft.missions[0]!;
    const fr = frFor(m);
    expect(checkMissionFr(m, fr)).toEqual([]);
    expect(checkMissionFr(m, { ...fr, expressions: [...fr.expressions.slice(1), { key: 'invented', meaning: 'x', contextNote: null, literalGloss: null }] })).toEqual([`missing ${m.expressions[0]!.key}`, 'unexpected invented']);
  });

  it('merges the French text, real titles and voices into a valid en+fr chapter without touching the target text', () => {
    const overlay = overlayFromFr(draft.missions.map((m) => ({ mission: m, fr: frFor(m) })), 'test-model');
    const voices = Object.fromEntries(draft.characters.map((c) => [c.characterKey, 'male' as const]));
    const chapter = defineSeedChapter(curriculumChapter(draft, overlay, voices, 'content-factory (test)', { en: 'First days in Moscow', fr: 'Premiers jours à Moscou' }));
    expect(chapter.key).toBe('russian_ch1');
    expect(chapter.sourceLanguages).toEqual(['en', 'fr']);
    expect(chapter.titles).toEqual({ en: 'First days in Moscow', fr: 'Premiers jours à Moscou' });
    expect(chapter.characters.every((c) => c.voice === 'male')).toBe(true);
    const e = chapter.missions[0]!.expressions[0]!;
    expect(e.meanings.fr?.meaning).toBe(`sens de ${e.key}`);
    expect(e.targetText).toBe(draft.missions[0]!.expressions[0]!.targetText);
    expect(chapter.nativeReviewed).toBe(false);
    expect(chapter.reviewStatus).toBe('review_needed');
  });

  it('throws when a phrase has no French meaning', () => {
    const overlay = overlayFromFr(draft.missions.map((m) => ({ mission: m, fr: frFor(m) })), 'test-model');
    const first = Object.keys(overlay.missions)[0]!;
    const holed = { ...overlay, missions: { ...overlay.missions, [first]: { ...overlay.missions[first]!, expressions: {} } } };
    expect(() => curriculumChapter(draft, holed, {}, 'x', { en: 'A', fr: 'B' })).toThrow(/missing fr meaning/);
  });

  it('a track that shares its assets gets the chapter under its own keys', () => {
    const mandarin = GENERATED_CHAPTERS.find((c) => c.courseTrackId === 'chinese-mandarin')!;
    const copy = defineSeedChapter(copyChapter(mandarin, 'chinese-simplified'));
    expect(copy.key).toBe('chinese_simplified_ch1');
    expect(copy.courseTrackId).toBe('chinese-simplified');
    expect(copy.missions.every((m) => m.key.startsWith('chinese_simplified_') && m.characterKey.startsWith('chinese_simplified_'))).toBe(true);
    expect(copy.missions[0]!.expressions[0]!.targetText).toBe(mandarin.missions[0]!.expressions[0]!.targetText);
  });

  it('writes the generated index in catalog order', () => {
    const src = generatedIndexSource(['vietnamese', 'russian', 'arabic-eastern']);
    expect(src.indexOf("from './arabic-eastern.json'")).toBeLessThan(src.indexOf("from './russian.json'"));
    expect(src).toContain('[arabicEastern, russian, vietnamese]');
    expect(src).toContain('GENERATED by scripts/src/import-factory-chapters.ts');
  });
});
